"""Notable objects: the famous things that carry no NGC / IC / Messier number,
or that people know by a name the big catalogues do not use. Quasars and
blazars, pulsars and magnetars, black holes, gravitational lenses, galaxy
groups and clusters, dwarf galaxies, record-holding stars, exoplanet hosts,
historical novae and supernovae, gamma-ray and fast radio bursts, deep
fields and a few sky landmarks (galactic poles, equinox points).
A search for "Phoenix A", "TON 618", "Vela pulsar", "Gaia BH3" or
"Cygnus X-1" finds them, and they show on the sky map whatever the
magnitude cap.

    python scripts/build-named-objects.py [--db path/to/dso.db]

Rows are written with catalog = 'Notable'; running again replaces them. The
table is hand-curated from SIMBAD / NED (J2000) and meant to stay famous:
this is not a catalogue mirror. Constellations follow the IAU boundaries
(checked with astropy's get_constellation when a batch is added).

The NICKNAMES table at the bottom is different: it adds popular imaging
nicknames ("Elephant Trunk", "Flame Nebula", "Tulip Nebula") to the
common_name of NGC / IC / Sh2 rows that the source catalogues list only by
number, so the search and the map label find them without a duplicate row.
"""
