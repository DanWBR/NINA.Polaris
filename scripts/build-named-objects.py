def hms(h, m, s):
    return h + m / 60 + s / 3600


def dms(sign, d, m, s):
    v = d + m / 60 + s / 3600
    return -v if sign < 0 else v


def o(cid, name, common, typ, ra, dec, mag, size, con, aliases):
    return (cid, name, common, typ, ra, dec, mag, size, con, aliases)


